-- ================================================================
-- 需求1：应用版本化管理
-- 为 app 表增加「当前版本号」字段
--   version = 0 表示该应用从未提交过版本（老应用默认即为 0，无需额外处理数据）
-- 说明：版本文件快照存放在文件系统（tmp/code_versions/{codeGenType}_{appId}/v{n}），
--      数据库只保存当前版本号指针，因此无需新增数据表
-- ================================================================
alter table app
    add column version int default 0 not null comment '当前版本号（0 表示从未提交版本）' after deployedTime;
