-- ================================================================
-- 需求5：部署控制（含按版本部署）
-- 为 app 表增加「线上内容来源的版本号」字段
--   null = 部署的是工作区最新内容（默认、也是历史数据的行为）
--   n    = 部署的是版本库中 v{n} 的代码快照
-- 该字段同时用于历史版本淘汰保护：线上正在部署的版本不会被清理
-- ================================================================
alter table app
    add column deployedVersion int null comment '线上内容来源的版本号（null 表示部署的是工作区最新内容）' after deployedTime;
